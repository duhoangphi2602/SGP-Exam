package poly.model;

public class GiaoVienDangKy {
    private String maGV;
    private String maMH;
    private String maLop;
    private String trinhDo;
    private String ngayThi;
    private int lan;
    private int soCauThi;
    private int thoiGian;

    public GiaoVienDangKy() {}

    public String getMaGV() { return maGV; }
    public void setMaGV(String maGV) { this.maGV = maGV; }
    public String getMaMH() { return maMH; }
    public void setMaMH(String maMH) { this.maMH = maMH; }
    public String getMaLop() { return maLop; }
    public void setMaLop(String maLop) { this.maLop = maLop; }
    public String getTrinhDo() { return trinhDo; }
    public void setTrinhDo(String trinhDo) { this.trinhDo = trinhDo; }
    public String getNgayThi() { return ngayThi; }
    public void setNgayThi(String ngayThi) { this.ngayThi = ngayThi; }
    public int getLan() { return lan; }
    public void setLan(int lan) { this.lan = lan; }
    public int getSoCauThi() { return soCauThi; }
    public void setSoCauThi(int soCauThi) { this.soCauThi = soCauThi; }
    public int getThoiGian() { return thoiGian; }
    public void setThoiGian(int thoiGian) { this.thoiGian = thoiGian; }
}